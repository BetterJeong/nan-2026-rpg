/** Boss monster id for apex zone (`boss` command) */
export const BOSS_BY_ZONE: Record<string, string> = {
  eldergrove: 'grove_guardian',
  abysscove: 'tide_leviathan',
  peakruin: 'tyrant',
}

/** Region requires this boss cleared before entry */
export const REGION_REQUIRED_BOSS: Record<ZoneDef['region'], string | null> = {
  forest: null,
  sea: 'grove_guardian',
  mountain: 'tide_leviathan',
}

export function getBossForZone(zoneId: string): string | undefined {
  return BOSS_BY_ZONE[zoneId]
}

export function requiredBossForZone(zone: ZoneDef): string | null {
  return REGION_REQUIRED_BOSS[zone.region]
}

export function hasDefeatedBoss(defeated: string[] | undefined, bossId: string): boolean {
  return Array.isArray(defeated) && defeated.includes(bossId)
}

/** Resolve zone by id, name, or alias */
export function findZone(query: string): ZoneDef | undefined {
  const q = query.trim().toLowerCase()
  return Object.values(ZONES).find(
    (z) =>
      z.id === q ||
      z.name.toLowerCase() === q ||
      z.name === query.trim() ||
      z.aliases?.some((a) => a === query.trim() || a.toLowerCase() === q),
  )
}

/** Migrate legacy forest1/2/3 save locations */
export function migrateLocationId(loc: string): string {
  const map: Record<string, string> = {
    forest1: 'mistwood',
    forest2: 'thornpath',
    forest3: 'eldergrove',
  }
  return map[loc] ?? loc
}


export function getItem(id: string): ItemDef | undefined {
  return ITEMS[id]
}

export function formatItemStats(item: ItemDef): string {
  const parts: string[] = []
  if (item.atk) parts.push(`ATK+${item.atk}`)
  if (item.def) parts.push(`DEF+${item.def}`)
  if (item.hp) parts.push(`HP+${item.hp}`)
  if (item.mp) parts.push(`MP+${item.mp}`)
  if (item.effect?.healHp) parts.push(`HP회복 ${item.effect.healHp}`)
  if (item.effect?.healMp) parts.push(`MP회복 ${item.effect.healMp}`)
  return parts.length ? parts.join(', ') : '효과 없음'
}
